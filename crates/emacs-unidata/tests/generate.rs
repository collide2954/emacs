use emacs_unidata::{charscript_el, emoji_zwj_el};

const BLOCKS: &str = "\
# Blocks-16.0.0.txt\r
0000..007F; Basic Latin\r
0080..00FF; Latin-1 Supplement\r
0100..017F; Latin Extended-A\r
0370..03FF; Greek and Coptic\r
E000..F8FF; Private Use Area\r
FE00..FE0F; Variation Selectors\r
10A0..10FF; Georgian\r
2C00..2C5F; Glagolitic\r
1E000..1E02F; Glagolitic Supplement\r
";

const EMOJI_DATA: &str = "\
231A..231B    ; Emoji_Presentation   # E0.6   [2] (watch..hourglass done)
23E9          ; Emoji_Presentation   # E0.6   [1] (fast-forward)
23EA          ; Emoji                # E0.6   [1] (rewind)
";

#[test]
fn charscript_entries() {
    let out = charscript_el(BLOCKS, EMOJI_DATA);
    let entries: Vec<&str> = out.lines().filter(|l| l.starts_with("    (#x")).collect();
    assert_eq!(
        entries,
        [
            "    (#x0000 #x007F latin) ; Basic Latin",
            "    (#x00A0 #x017F latin) ; Latin-1 Supplement, Latin Extended-A",
            "    (#x0370 #x03E1 greek) ; Greek and Coptic",
            "    (#x03E2 #x03EF coptic)",
            "    (#x03F0 #x03FF greek)",
            "    (#x10A0 #x10FF georgian)",
            "    (#x2C00 #x2C5F glagolitic)",
            "    (#x1E000 #x1E02F glagolitic) ; Glagolitic Supplement",
            "    (#x231A #x231B emoji) ; Autogenerated emoji",
            "    (#x23E9 #x23E9 emoji) ; Autogenerated emoji",
            "    (#xFE0F #xFE0F emoji) ; Autogenerated emoji (override)",
        ]
    );
    assert!(
        out.starts_with(
            ";;; charscript.el --- character script table  -*- lexical-binding:t -*-\n"
        )
    );
    assert!(out.contains("  (set-char-table-extra-slot char-script-table 0 (nreverse script-list)))\n\n(map-char-table\n"));
    assert!(out.ends_with(" char-script-table)\n\n(provide 'charscript)\n"));
}

#[test]
fn emoji_zwj_sequences() {
    let zwj = "\
1F468 200D 1F4BB                            ; RGI_Emoji_ZWJ_Sequence  ; man technologist  # E4.0
1F468 1F3FB 200D 1F4BB                      ; RGI_Emoji_ZWJ_Sequence  ; man technologist: light skin tone  # E4.0
";
    let sequences =
        "1F44B 1F3FB   ; RGI_Emoji_Modifier_Sequence  ; waving hand: light skin tone  # E1.0\n";
    let variation =
        "231A FE0F ; emoji style; # (1.1) WATCH\n231A FE0E ; text style;  # (1.1) WATCH\n";
    let test = "1F441 200D 1F5E8                                       ; unqualified          # eye in speech bubble\n";
    let out = emoji_zwj_el(&[zwj, sequences, variation, test]);
    assert!(
        out.contains(
            "(setq auto-composition-emoji-tty-eligible-codepoints\n'(\n?\\N{U+231A}\n))\n"
        )
    );
    assert!(out.contains(
        "(setq auto-composition-emoji-unqualified-tail-initials\n'(\n?\\N{U+1F5E8}\n))\n"
    ));
    assert!(out.contains(
        "(#x1F468 .\n,(regexp-opt\n'(\n\"\\N{U+1F468}\\N{U+200D}\\N{U+1F4BB}\"\n\"\\N{U+1F468}\\N{U+1F3FB}\\N{U+200D}\\N{U+1F4BB}\"\n\"\\N{U+1F468}\\N{U+FE0E}\"\n\"\\N{U+1F468}\\N{U+FE0F}\"\n)))\n"
    ));
    assert!(out.contains("(#x1F44B .\n"));
    assert!(out.contains("(#x1F441 .\n"));
    let first_trigger = out.find("?\\N{U+261D}").expect("trigger list");
    let last_trigger = out.find("?\\N{U+26D3}").expect("trigger list");
    assert!(first_trigger < last_trigger);
    assert!(out.ends_with("\n(provide 'emoji-zwj)"));
}
