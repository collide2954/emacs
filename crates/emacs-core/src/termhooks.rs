#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum EventKind {
    #[default]
    NoEvent,
    AsciiKeystroke,
    MultibyteCharKeystroke,
    NonAsciiKeystroke,
    Timer,
    MouseClick,
    Wheel,
    HorizWheel,
    ScrollBarClick,
    HorizontalScrollBarClick,
    SelectionRequest,
    SelectionClear,
    DeleteWindow,
    MenuBar,
    Iconify,
    Deiconify,
    MenuBarActivate,
    DragNDrop,
    UserSignal,
    Help,
    TabBar,
    ToolBar,
    FocusIn,
    FocusOut,
    MoveFrame,
    SelectWindow,
    SaveSession,
    Thread,
    ConfigChanged,
    FileNotify,
    Sleep,
    PreeditText,
    TouchEnd,
    TouchscreenUpdate,
    TouchscreenBegin,
    TouchscreenEnd,
    Pinch,
    MonitorsChanged,
    ToolkitThemeChanged,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum ScrollBarPart {
    #[default]
    Nowhere,
    AboveHandle,
    Handle,
    BelowHandle,
    UpArrow,
    DownArrow,
    ToTop,
    ToBottom,
    EndScroll,
    MoveRatio,
    BeforeHandle,
    HorizontalHandle,
    AfterHandle,
    LeftArrow,
    RightArrow,
    ToLeftmost,
    ToRightmost,
}

#[derive(Clone, PartialEq, Eq, Debug, Default)]
pub struct InputEvent {
    pub kind: EventKind,
    pub part: ScrollBarPart,
    pub code: u32,
    pub modifiers: i64,
    pub x: i64,
    pub y: i64,
    pub timestamp: u64,
    pub frame: u64,
    pub arg: Option<String>,
}
